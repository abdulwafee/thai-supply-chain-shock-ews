def load_artifact_bundle(root: Path | str, *, policy: ScenarioPolicy | None = None,
                         policy_path: Path | str | None = None) -> ArtifactBundle:
    """Verify and load the four pinned artifacts beneath ``root``.

    ``root`` is explicit so a test can point the loader at a temporary tree without the
    module guessing anything. Every artifact is digest-checked before it is parsed, and
    the parsed dataset is then checked against the policy and against itself.
    """
    root_path = Path(root)
    if not root_path.is_dir():
        raise ArtifactIntegrityError(f"repository root {root} is not a directory")
    declarations = read_artifact_declarations(policy_path)
    policy = policy or load_policy(policy_path)
    payloads = {d.name: _verified_bytes(root_path, d) for d in declarations}
    by_name = {d.name: d for d in declarations}

    industries = _industries(payloads["industry_map"], by_name["industry_map"])
    industry_ids = {industry.industry_id for industry in industries}
    industry_names = {i.industry_id: i.name_en for i in industries}

    channel_sectors = {entry.channel: entry.io_sector_code for entry in policy.channels}
    if set(channel_sectors) != set(REGISTERED_CHANNELS):
        raise ArtifactIntegrityError(
            f"policy channels {sorted(channel_sectors)} are not the registered set "
            f"{sorted(REGISTERED_CHANNELS)}"
        )

    pairs = _exposure_pairs(payloads, by_name, industry_ids, industry_names, channel_sectors)
    mediators = _mediators(payloads, by_name, {p.key for p in pairs})
    price_stages = _price_stages(payloads, by_name, {p.key for p in pairs})
    _cross_check(pairs, mediators, price_stages, policy_path)

    reference_year = policy.structural_reference_year
    return ArtifactBundle(
        declarations=declarations,
        industries=industries,
        pairs=pairs,
        mediators=mediators,
        price_stages=price_stages,
        channel_sectors=dict(sorted(channel_sectors.items())),
        structural_reference_year=reference_year,
    )


def _exposure_pairs(payloads, by_name, industry_ids, industry_names, channel_sectors) -> tuple:
    declaration = by_name["exposure_matrix"]
    document = _json_document(payloads["exposure_matrix"], declaration)
    rows = _rows(document, "canonical_rows", declaration)
    if len(rows) != EXPECTED_PAIR_COUNT:
        raise ArtifactIntegrityError(
            f"{declaration.name}: expected {EXPECTED_PAIR_COUNT} canonical rows, found {len(rows)}"
        )
    crosswalk = document.get("commodity_crosswalk")
    if not isinstance(crosswalk, dict):
        raise ArtifactIntegrityError(f"{declaration.name}: commodity_crosswalk is missing")

    pairs = []
    seen = set()
    for index, row in enumerate(rows):
        at = f"{declaration.name}:canonical_rows[{index}]"
        industry_id = _text_field(row, "industry_id", where=at)
        channel = _text_field(row, "commodity_series_id", where=at)
        if industry_id not in industry_ids:
            raise ArtifactIntegrityError(f"{at}: unexpected industry {industry_id!r}")
        if channel not in channel_sectors:
            raise ArtifactIntegrityError(f"{at}: unexpected channel {channel!r}")
        key = (industry_id, channel)
        if key in seen:
            raise ArtifactIntegrityError(f"{at}: duplicate industry/channel pair {key}")
        seen.add(key)
        sector = _text_field(row, "commodity_io_sector_code", where=at)
        if sector != channel_sectors[channel]:
            raise ArtifactIntegrityError(
                f"{at}: channel {channel!r} maps to sector {sector!r} here and to "
                f"{channel_sectors[channel]!r} in the policy"
            )
        declared_sector = crosswalk.get(channel, {}).get("io_sector_code")
        if declared_sector != sector:
            raise ArtifactIntegrityError(
                f"{at}: crosswalk sector {declared_sector!r} disagrees with row sector {sector!r}"
            )
        name = _text_field(row, "industry_name", where=at)
        if name != industry_names[industry_id]:
            raise ArtifactIntegrityError(
                f"{at}: industry name {name!r} disagrees with the industry map "
                f"({industry_names[industry_id]!r})"
            )
        direct = _decimal(row, "direct_exposure", where=at)
        total = _decimal(row, "total_requirement_exposure", where=at)
        published_indirect = _decimal(row, "indirect_exposure", where=at)
        if direct < 0 or total < 0:
            raise ArtifactIntegrityError(f"{at}: exposures must be non-negative")
        if total < direct:
            raise ArtifactIntegrityError(
                f"{at}: total requirement {total} is below direct {direct}, so the propagated "
                "component would be negative"
            )
        sign = row.get("price_increase_to_stress_sign")
        if sign is not None and sign not in (1, -1):
            raise ArtifactIntegrityError(f"{at}: sign {sign!r} is neither null, 1 nor -1")
        eligible = row.get("industry_pair_feature_eligible")
        if not isinstance(eligible, bool):
            raise ArtifactIntegrityError(f"{at}: industry_pair_feature_eligible must be boolean")
        channel_kind = _text_field(row, "direction_channel", where=at)
        if sign is None and eligible:
            raise ArtifactIntegrityError(
                f"{at}: the pair is eligible but its direction sign is null, which cannot both "
                "be true"
            )
        if channel_kind == "mixed_or_ambiguous" and sign is not None:
            raise ArtifactIntegrityError(
                f"{at}: direction channel is mixed_or_ambiguous but a sign is published"
            )
        pairs.append(
            ExposurePair(
                industry_id=industry_id,
                industry_name=name,
                channel=channel,
                io_sector_code=sector,
                direct_exposure=direct,
                total_requirement_exposure=total,
                published_indirect_exposure=published_indirect,
                sign=sign,
                direction_channel=channel_kind,
                feature_eligible=eligible,
                proxy_fit_status=_text_field(row, "commodity_proxy_fit_status", where=at),
                quality_flag=_text_field(row, "quality_flag", where=at),
            )
        )
    expected_keys = {(i, c) for i in industry_ids for c in channel_sectors}
    if seen != expected_keys:
        raise ArtifactIntegrityError(
            f"{declaration.name}: pair coverage is incomplete; missing "
            f"{sorted(expected_keys - seen)}"
        )
    return tuple(sorted(pairs, key=lambda p: (p.industry_id, p.channel)))


def _mediators(payloads, by_name, pair_keys) -> tuple:
    declaration = by_name["structural_path_audit"]
    document = _json_document(payloads["structural_path_audit"], declaration)
    rows = _rows(document, "mediator_table", declaration)
    expected_total = EXPECTED_PAIR_COUNT * EXPECTED_MEDIATORS_PER_PAIR
    if len(rows) != expected_total:
        raise ArtifactIntegrityError(
            f"{declaration.name}: expected {expected_total} mediator rows, found {len(rows)}"
        )
    mediators = []
    identities = set()
    per_pair: dict = {}
    for index, row in enumerate(rows):
        at = f"{declaration.name}:mediator_table[{index}]"
        industry_id = _text_field(row, "industry_id", where=at)
        channel = _text_field(row, "commodity_series_id", where=at)
        key = (industry_id, channel)
        if key not in pair_keys:
            raise ArtifactIntegrityError(f"{at}: mediator names an unknown pair {key}")
        rank = row.get("rank")
        if not isinstance(rank, int) or isinstance(rank, bool) or not 1 <= rank <= (
            EXPECTED_MEDIATORS_PER_PAIR
        ):
            raise ArtifactIntegrityError(
                f"{at}: rank {rank!r} is not an integer in 1..{EXPECTED_MEDIATORS_PER_PAIR}"
            )
        identity = (industry_id, channel, rank)
        if identity in identities:
            raise ArtifactIntegrityError(f"{at}: duplicate mediator identity {identity}")
        identities.add(identity)
        per_pair[key] = per_pair.get(key, 0) + 1
        mediators.append(
            Mediator(
                industry_id=industry_id,
                channel=channel,
                rank=rank,
                intermediate_sector_code=_text_field(row, "intermediate_sector_code", where=at),
                intermediate_sector_label=_text_field(row, "intermediate_sector_label", where=at),
                contribution=_decimal(row, "indirect_via_sector", where=at),
                share_of_indirect=_decimal(row, "share_of_indirect", where=at),
                cumulative_share=_decimal(row, "cumulative_share", where=at),
                pair_direct_exposure=_decimal(row, "direct_exposure", where=at),
                pair_total_exposure=_decimal(row, "total_exposure", where=at),
            )
        )
    wrong = {k: v for k, v in per_pair.items() if v != EXPECTED_MEDIATORS_PER_PAIR}
    if wrong or set(per_pair) != pair_keys:
        raise ArtifactIntegrityError(
            f"{declaration.name}: every pair needs exactly {EXPECTED_MEDIATORS_PER_PAIR} "
            f"mediators; offending {sorted(wrong) or sorted(pair_keys - set(per_pair))}"
        )
    return tuple(sorted(mediators, key=lambda m: (m.industry_id, m.channel, m.rank)))


def _price_stages(payloads, by_name, pair_keys) -> tuple:
    declaration = by_name["price_stage_source_audit"]
    document = _json_document(payloads["price_stage_source_audit"], declaration)
    rows = _rows(document, "price_stage_alignment", declaration)
    if len(rows) != EXPECTED_PAIR_COUNT:
        raise ArtifactIntegrityError(
            f"{declaration.name}: expected {EXPECTED_PAIR_COUNT} price-stage records, found "
            f"{len(rows)}"
        )
    stages = []
    seen = set()
    for index, row in enumerate(rows):
        at = f"{declaration.name}:price_stage_alignment[{index}]"
        industry_id = _text_field(row, "industry_id", where=at)
        channel = _text_field(row, "commodity_series_id", where=at)
        key = (industry_id, channel)
        if key not in pair_keys:
            raise ArtifactIntegrityError(f"{at}: price-stage record names an unknown pair {key}")
        if key in seen:
            raise ArtifactIntegrityError(f"{at}: duplicate price-stage record for {key}")
        seen.add(key)
        stages.append(
            PriceStage(
                industry_id=industry_id,
                channel=channel,
                price_stage=_text_field(row, "price_stage", where=at),
                alignment_status=_text_field(row, "alignment_status", where=at),
                mapped_io_sector_code=_text_field(row, "mapped_raw_io_sector", where=at),
                limitations=_text_field(row, "limitations", where=at),
                shared_source_sector_warning=_text_field(
                    row, "shared_source_sector_warning", where=at, allow_null=True
                ),
                pair_direct_exposure=_decimal(row, "direct_exposure", where=at),
                pair_total_exposure=_decimal(row, "total_exposure", where=at),
            )
        )
    if seen != pair_keys:
        raise ArtifactIntegrityError(
            f"{declaration.name}: price-stage coverage is incomplete; missing "
            f"{sorted(pair_keys - seen)}"
        )
    return tuple(sorted(stages, key=lambda s: (s.industry_id, s.channel)))


def _cross_check(pairs, mediators, price_stages, policy_path) -> None:
    """C5's own coefficients must agree with C3's within the declared tolerance."""
    raw = _policy_mapping(policy_path)
    agreement = raw.get("cross_artifact_agreement")
    if not isinstance(agreement, dict):
        raise ScenarioPolicyError("policy: cross_artifact_agreement is missing")
    if agreement.get("authoritative_coefficient_source") != "exposure_matrix":
        raise ScenarioPolicyError(
            "policy: the exposure matrix must be the authoritative coefficient source"
        )
    if agreement.get("supporting_artifacts_are_scored") is not False:
        raise ScenarioPolicyError("policy: supporting_artifacts_are_scored must be false")
    if agreement.get("tolerance_is_a_learned_threshold") is not False:
        raise ScenarioPolicyError(
            "policy: tolerance_is_a_learned_threshold must be false — this bound is declared "
            "validation policy and presenting it as estimated would be a false claim"
        )
    tolerance = agreement.get("coefficient_agreement_tolerance")
    if isinstance(tolerance, bool) or not isinstance(tolerance, (int, Decimal)):
        raise ScenarioPolicyError("policy: coefficient_agreement_tolerance must be a number")
    tolerance = Decimal(tolerance)
    if tolerance <= 0:
        raise ScenarioPolicyError("policy: coefficient_agreement_tolerance must be positive")

    by_key = {pair.key: pair for pair in pairs}
    first_mediator = {}
    for mediator in mediators:
        first_mediator.setdefault((mediator.industry_id, mediator.channel), mediator)

    def compare(label, key, left, right):
        difference = abs(left - right)
        if difference > tolerance:
            raise ArtifactIntegrityError(
                f"{key[0]}/{key[1]}: {label} disagrees between the exposure matrix ({left}) and "
                f"the supporting artifact ({right}); the difference {difference} exceeds the "
                f"declared agreement tolerance {tolerance}"
            )

    for key, pair in by_key.items():
        mediator = first_mediator.get(key)
        if mediator is None:
            raise ArtifactIntegrityError(f"{key}: no mediator rows for a published pair")
        compare("mediator direct exposure", key, pair.direct_exposure,
                mediator.pair_direct_exposure)
        compare("mediator total exposure", key, pair.total_requirement_exposure,
                mediator.pair_total_exposure)
    for stage in price_stages:
        key = (stage.industry_id, stage.channel)
        pair = by_key[key]
        if stage.mapped_io_sector_code != pair.io_sector_code:
            raise ArtifactIntegrityError(
                f"{stage.industry_id}/{stage.channel}: price-stage sector "
                f"{stage.mapped_io_sector_code!r} disagrees with the exposure matrix "
                f"({pair.io_sector_code!r})"
            )
        compare("price-stage direct exposure", key, pair.direct_exposure,
                stage.pair_direct_exposure)
        compare("price-stage total exposure", key, pair.total_requirement_exposure,
                stage.pair_total_exposure)
