#: The four logical artifacts, in the order the policy declares them.
ARTIFACT_NAMES = (
    "exposure_matrix",
    "structural_path_audit",
    "price_stage_source_audit",
    "industry_map",
)

#: Representations a declaration may name. Anything else is refused rather than
#: guessed: an unrecognised representation means the pin's meaning is unknown, and a
#: digest whose meaning is unknown verifies nothing.
SUPPORTED_DIGEST_REPRESENTATIONS = frozenset({CANONICAL_LF, RAW_BYTES})

EXPECTED_INDUSTRY_COUNT = 12
EXPECTED_PAIR_COUNT = 48
EXPECTED_MEDIATORS_PER_PAIR = 10


class ArtifactIntegrityError(RuntimeError):
    """A published artifact is missing, altered, unreadable or internally wrong.

    A sibling of :class:`~thai_supply_chain_ews.scenario.contract.ScenarioPolicyError`
    rather than of the contract errors, and for the same reason: this is never the
    user's fault and cannot be fixed by editing a scenario. It is a shipped-artifact
    integrity failure, and the future command-line layer maps both onto one exit code.
    """


@dataclass(frozen=True)
class ArtifactDeclaration:
    """One pinned artifact, exactly as the policy declares it."""

    name: str
    path: str
    fmt: str
    sha256: str
    digest_representation: str
    role: str

    def digest_of(self, data: bytes) -> str:
        if self.digest_representation == CANONICAL_LF:
            return canonical_digest(data)
        return digest(data)


@dataclass(frozen=True)
class Industry:
    """One project industry, from ``data/mapping/industry_map.csv``."""

    industry_id: str
    name_en: str
    tsic_divisions: tuple[str, ...]
    status: str


@dataclass(frozen=True)
class Mediator:
    """One ``commodity -> intermediate sector -> industry`` attribution row."""

    industry_id: str
    channel: str
    rank: int
    intermediate_sector_code: str
    intermediate_sector_label: str
    contribution: Decimal
    share_of_indirect: Decimal
    cumulative_share: Decimal
    pair_direct_exposure: Decimal
    pair_total_exposure: Decimal


@dataclass(frozen=True)
class PriceStage:
    """Price-stage alignment metadata for one industry/channel pair."""

    industry_id: str
    channel: str
    price_stage: str
    alignment_status: str
    mapped_io_sector_code: str
    limitations: str
    shared_source_sector_warning: str | None
    pair_direct_exposure: Decimal
    pair_total_exposure: Decimal


@dataclass(frozen=True)
class ExposurePair:
    """One industry/channel pair, as published.

    ``propagated_exposure`` is **derived** as ``total - direct`` rather than read from
    the published ``indirect_exposure``. The artifact's three coefficients were written
    by float64 arithmetic and do not satisfy ``direct + indirect == total`` exactly —
    they disagree by up to 6e-17. Deriving the component makes the identity true by
    construction instead of nearly true by luck. The published field is kept beside it,
    unaltered, because it is what the artifact says.
    """

    industry_id: str
    industry_name: str
    channel: str
    io_sector_code: str
    direct_exposure: Decimal
    total_requirement_exposure: Decimal
    published_indirect_exposure: Decimal
    sign: int | None
    direction_channel: str
    feature_eligible: bool
    proxy_fit_status: str
    quality_flag: str

    @property
    def propagated_exposure(self) -> Decimal:
        return self.total_requirement_exposure - self.direct_exposure

    @property
    def key(self) -> tuple[str, str]:
        return (self.industry_id, self.channel)

    def coefficient(self, basis: str) -> Decimal:
        if basis == "direct":
            return self.direct_exposure
        if basis == "total_requirement":
            return self.total_requirement_exposure
        raise ArtifactIntegrityError(
            f"internal: unknown basis {basis!r} reached coefficient selection"
        )


@dataclass(frozen=True)
class ArtifactBundle:
    """Every verified artifact, keyed for the calculation engine."""

    declarations: tuple[ArtifactDeclaration, ...]
    industries: tuple[Industry, ...]
    pairs: tuple[ExposurePair, ...]
    mediators: tuple[Mediator, ...]
    price_stages: tuple[PriceStage, ...]
    channel_sectors: dict
    structural_reference_year: int

    @property
    def industry_ids(self) -> tuple[str, ...]:
        return tuple(industry.industry_id for industry in self.industries)

    @property
    def industry_names(self) -> dict:
        return {industry.industry_id: industry.name_en for industry in self.industries}

    def pair(self, industry_id: str, channel: str) -> ExposurePair | None:
        for entry in self.pairs:
            if entry.industry_id == industry_id and entry.channel == channel:
                return entry
        return None

    def mediators_for(self, industry_id: str, channel: str) -> tuple[Mediator, ...]:
        return tuple(
            m for m in self.mediators if m.industry_id == industry_id and m.channel == channel
        )

    def price_stage_for(self, industry_id: str, channel: str) -> PriceStage | None:
        for entry in self.price_stages:
            if entry.industry_id == industry_id and entry.channel == channel:
                return entry
        return None

    def digest_of(self, name: str) -> str:
        for declaration in self.declarations:
            if declaration.name == name:
                return declaration.sha256
        raise ArtifactIntegrityError(f"no artifact named {name!r}")


