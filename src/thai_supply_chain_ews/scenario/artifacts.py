"""The published artifacts the calculation may read, and nothing else.

Phase 1 decided what a user may ask. This module decides what the answer may be
computed from, and the two are separate trust problems. A scenario document is
untrusted because a person wrote it; these four files are trusted because they were
published, reviewed and pinned — which is only true for as long as something checks
that the bytes on disk are still the bytes that were pinned.

**The set is closed and named.** Four artifacts, each declared individually in
``configs/structural_exposure_scenario.yaml`` with its own path and digest. No
directory scan, no glob, no "load whatever is in docs/". A tool that discovers its own
inputs is a tool whose inputs can change without anybody deciding they should.

**The pins are the scenario's own.** ``docs/e2r1_release_manifest.json`` is a frozen
record of one publication; reading it at runtime would make an immutable historical
document into a live registry, and a future release row would quietly become a runtime
dependency. The two agree today, and a test checks that they agree — a different and
safer relationship than depending on one.

**Digests are canonical, not raw.** Two of the four files are stored LF in Git and
checked out CRLF on Windows. A raw-byte pin would verify on one platform and fail on
the other for a file nobody had edited, which is precisely the defect Task CI-R1 was
created to fix. Every pin here is
:func:`~thai_supply_chain_ews.release.byte_provenance.canonical_digest`, and the
representation is declared beside the value rather than assumed.

**C3 is authoritative; C5 is corroboration.** The exposure matrix supplies every
coefficient, sign and eligibility flag the arithmetic uses. The two C5 documents supply
mediator attribution and price-stage metadata, and their own copies of the coefficients
are checked for agreement within a declared tolerance but never scored. They were
generated by separate float64 runs and differ in the last digit or two for fourteen of
the forty-eight pairs; requiring exact equality would fail on arithmetic noise, and
ignoring the comparison entirely would let a genuinely different artifact through.

Nothing here reaches the network, writes a file, repairs an artifact, or falls back to
an unpinned copy of anything.
"""

