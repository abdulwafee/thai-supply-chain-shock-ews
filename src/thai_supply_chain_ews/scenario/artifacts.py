def _json_document(data: bytes, declaration: ArtifactDeclaration) -> dict:
    """Parse a pinned JSON artifact with every number as an exact decimal."""
    try:
        loaded = json.loads(data.decode("utf-8"), parse_float=Decimal, parse_constant=Decimal)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} is not valid UTF-8 JSON: {exc}"
        ) from exc
    if not isinstance(loaded, dict):
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} must be a JSON object"
        )
    return loaded


def _rows(document: dict, key: str, declaration: ArtifactDeclaration) -> list:
    rows = document.get(key)
    if not isinstance(rows, list) or not rows:
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} has no non-empty {key!r} array"
        )
    for index, row in enumerate(rows):
        if not isinstance(row, dict):
            raise ArtifactIntegrityError(
                f"{declaration.name}: {key}[{index}] is not an object"
            )
    return rows


def _decimal(row: dict, key: str, *, where: str, allow_null: bool = False) -> Decimal | None:
    value = row.get(key, "__missing__")
    if value == "__missing__":
        raise ArtifactIntegrityError(f"{where}: required field {key!r} is missing")
    if value is None:
        if allow_null:
            return None
        raise ArtifactIntegrityError(f"{where}: {key!r} is null where a number is required")
    if isinstance(value, bool) or not isinstance(value, (int, Decimal)):
        raise ArtifactIntegrityError(
            f"{where}: {key!r} must be a number, got {type(value).__name__}. A float here would "
            "mean the artifact was parsed without exact decimals"
        )
    result = value if isinstance(value, Decimal) else Decimal(value)
    if not result.is_finite():
        raise ArtifactIntegrityError(f"{where}: {key!r} is not finite")
    return result


def _text_field(row: dict, key: str, *, where: str, allow_null: bool = False) -> str | None:
    value = row.get(key, "__missing__")
    if value == "__missing__":
        raise ArtifactIntegrityError(f"{where}: required field {key!r} is missing")
    if value is None:
        if allow_null:
            return None
        raise ArtifactIntegrityError(f"{where}: {key!r} is null where text is required")
    if not isinstance(value, str):
        raise ArtifactIntegrityError(f"{where}: {key!r} must be text, got {type(value).__name__}")
    return value


def _industries(data: bytes, declaration: ArtifactDeclaration) -> tuple:
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} is not valid UTF-8"
        ) from exc
    reader = csv.DictReader(io.StringIO(text, newline=""))
    expected = ["industry_id", "name_en", "name_th", "tsic_divisions", "status", "source_of_truth"]
    if reader.fieldnames != expected:
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} columns are {reader.fieldnames}, expected "
            f"{expected}"
        )
    industries = []
    seen = set()
    for index, row in enumerate(reader):
        at = f"{declaration.name}:row[{index}]"
        industry_id = (row.get("industry_id") or "").strip()
        name_en = (row.get("name_en") or "").strip()
        if not industry_id or not name_en:
            raise ArtifactIntegrityError(f"{at}: industry_id and name_en are required")
        if industry_id in seen:
            raise ArtifactIntegrityError(f"{at}: duplicate industry_id {industry_id!r}")
        seen.add(industry_id)
        industries.append(
            Industry(
                industry_id=industry_id,
                name_en=name_en,
                tsic_divisions=tuple(
                    part for part in (row.get("tsic_divisions") or "").split(";") if part
                ),
                status=(row.get("status") or "").strip(),
            )
        )
    if len(industries) != EXPECTED_INDUSTRY_COUNT:
        raise ArtifactIntegrityError(
            f"{declaration.name}: expected {EXPECTED_INDUSTRY_COUNT} industries, found "
            f"{len(industries)}"
        )
    return tuple(sorted(industries, key=lambda item: item.industry_id))


