def _resolve_within(root: Path, relative: str, *, name: str) -> Path:
    """Resolve a declared artifact path, refusing every way out of the root.

    Spelling is checked first so the message names the rule that was broken, and
    resolution is checked afterwards because spelling is not what decides where a
    path lands: a symbolic link can be entirely well-behaved on paper.
    """
    if not relative:
        raise ArtifactIntegrityError(f"{name}: artifact path is empty")
    candidate = Path(relative)
    if candidate.is_absolute():
        raise ArtifactIntegrityError(f"{name}: artifact path {relative!r} is absolute")
    if candidate.drive or relative[1:2] == ":":
        raise ArtifactIntegrityError(f"{name}: artifact path {relative!r} is drive-qualified")
    if relative.startswith(("/", "\\")):
        raise ArtifactIntegrityError(
            f"{name}: artifact path {relative!r} starts with a separator, so it is not relative "
            "to the repository root"
        )
    if ".." in candidate.parts:
        raise ArtifactIntegrityError(
            f"{name}: artifact path {relative!r} contains '..' and could leave the repository"
        )
    root_real = Path(root).resolve()
    resolved = (root_real / candidate).resolve()
    if not resolved.is_relative_to(root_real):
        raise ArtifactIntegrityError(
            f"{name}: artifact path {relative!r} resolves to {resolved}, outside the repository "
            f"root {root_real}"
        )
    return resolved


def _verified_bytes(root: Path, declaration: ArtifactDeclaration) -> bytes:
    path = _resolve_within(root, declaration.path, name=declaration.name)
    if not path.exists():
        raise ArtifactIntegrityError(
            f"{declaration.name}: pinned artifact {declaration.path} is missing. It is never "
            "regenerated and there is no unpinned fallback"
        )
    if not path.is_file():
        raise ArtifactIntegrityError(f"{declaration.name}: {declaration.path} is not a file")
    data = path.read_bytes()
    actual = declaration.digest_of(data)
    if actual != declaration.sha256:
        raise ArtifactIntegrityError(
            f"{declaration.name}: {declaration.path} does not match its pin. Expected "
            f"{declaration.sha256} ({declaration.digest_representation}), measured {actual}. The "
            "artifact is not repaired and the calculation does not proceed"
        )
    return data


