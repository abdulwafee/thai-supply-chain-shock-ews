def read_artifact_declarations(policy_path: Path | str | None = None) -> tuple:
    """Read and validate the four artifact declarations from the policy file.

    Refuses a declaration set that is the wrong size, names an unexpected artifact,
    repeats a logical name, repeats a path, omits a required field, or names a digest
    representation this module does not implement.
    """
    raw = _policy_mapping(policy_path)
    entries = raw.get("runtime_artifacts")
    if not isinstance(entries, list):
        raise ScenarioPolicyError("policy: runtime_artifacts must be a list of declarations")
    if raw.get("runtime_artifacts_are_a_closed_set") is not True:
        raise ScenarioPolicyError("policy: runtime_artifacts_are_a_closed_set must be true")
    if raw.get("runtime_artifacts_discovered_by_scan") is not False:
        raise ScenarioPolicyError("policy: runtime_artifacts_discovered_by_scan must be false")
    if raw.get("runtime_artifacts_fall_back_to_unpinned") is not False:
        raise ScenarioPolicyError("policy: runtime_artifacts_fall_back_to_unpinned must be false")
    if raw.get("historical_release_manifest_is_a_runtime_registry") is not False:
        raise ScenarioPolicyError(
            "policy: historical_release_manifest_is_a_runtime_registry must be false — a frozen "
            "publication record is not a live artifact registry"
        )

    declarations: list[ArtifactDeclaration] = []
    seen_names: set[str] = set()
    seen_paths: set[str] = set()
    for index, entry in enumerate(entries):
        at = f"policy:runtime_artifacts[{index}]"
        if not isinstance(entry, dict):
            raise ScenarioPolicyError(f"{at}: each declaration must be a mapping")
        name = _required_text(entry, "name", where=at)
        path = _required_text(entry, "path", where=at)
        fmt = _required_text(entry, "format", where=at)
        sha = _required_text(entry, "sha256", where=at)
        representation = _required_text(entry, "digest_representation", where=at)
        if name not in ARTIFACT_NAMES:
            raise ScenarioPolicyError(
                f"{at}: {name!r} is not a runtime artifact of this release; expected one of "
                f"{list(ARTIFACT_NAMES)}"
            )
        if name in seen_names:
            raise ScenarioPolicyError(f"{at}: duplicate logical artifact name {name!r}")
        if path in seen_paths:
            raise ScenarioPolicyError(f"{at}: duplicate artifact path {path!r}")
        if representation not in SUPPORTED_DIGEST_REPRESENTATIONS:
            raise ScenarioPolicyError(
                f"{at}: digest_representation {representation!r} is not implemented; a pin whose "
                f"representation is unknown verifies nothing. Expected one of "
                f"{sorted(SUPPORTED_DIGEST_REPRESENTATIONS)}"
            )
        if fmt not in ("json", "csv"):
            raise ScenarioPolicyError(f"{at}: format {fmt!r} is not json or csv")
        if len(sha) != 64 or any(c not in "0123456789abcdef" for c in sha):
            raise ScenarioPolicyError(f"{at}: sha256 {sha!r} is not 64 lower-case hex characters")
        seen_names.add(name)
        seen_paths.add(path)
        declarations.append(
            ArtifactDeclaration(
                name=name, path=path, fmt=fmt, sha256=sha,
                digest_representation=representation,
                role=str(entry.get("role", "")).strip(),
            )
        )
    missing = [name for name in ARTIFACT_NAMES if name not in seen_names]
    if missing:
        raise ScenarioPolicyError(f"policy: runtime artifact declarations missing {missing}")
    return tuple(declarations)


def _policy_mapping(policy_path: Path | str | None):
    """The raw policy mapping, read through the contract module's own policy loader."""
    path = Path(policy_path) if policy_path is not None else DEFAULT_POLICY_PATH
    if not path.is_file():
        raise ScenarioPolicyError(f"scenario policy configuration not found: {path}")
    try:
        raw = yaml.load(path.read_text(encoding="utf-8"), Loader=_PolicyLoader)
    except Exception as exc:  # noqa: BLE001 - any parse failure is one policy defect
        raise ScenarioPolicyError(f"{path}: policy could not be parsed: {exc}") from exc
    if not isinstance(raw, dict):
        raise ScenarioPolicyError(f"{path}: policy must be a mapping")
    return raw


def _required_text(mapping: dict, key: str, *, where: str) -> str:
    value = mapping.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ScenarioPolicyError(f"{where}: {key!r} must be a non-empty string")
    return value.strip()


